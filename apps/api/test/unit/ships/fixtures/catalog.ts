export const CATALOG_BY_TYPE: ReadonlyMap<string, PartCatalog> = new Map(
  CATALOG_PARTS.map((part) => [part.partType, part]),
);

export function freshInstalled(partType: string): { instance: { id: string; partType: string; condition: number }; catalog: PartCatalog } {
  const catalog = CATALOG_BY_TYPE.get(partType);
  if (catalog === undefined) {
    throw new Error(`Unknown part type: ${partType}`);
  }
  return {
    instance: { id: `${partType}-instance`, partType, condition: 100 },
    catalog,
  };
}

export function buildInstalled(partTypes: readonly string[]): ReturnType<typeof freshInstalled>[] {
  return partTypes.map((type, index) => ({
    instance: { id: `${type}-${index}`, partType: type, condition: 100 },
    catalog: CATALOG_BY_TYPE.get(type)!,
  }));
}

export function catalogByInstanceId(
  parts: ReturnType<typeof buildInstalled>,
): ReadonlyMap<string, PartCatalog> {
  return new Map(parts.map((part) => [part.instance.id, part.catalog]));
}
